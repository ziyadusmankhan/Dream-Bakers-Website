import { setupValidation, validateForm } from './forms.js';
import { openWhatsApp } from './whatsapp.js';
const form = document.getElementById('contactForm');
const feedback = document.getElementById('formFeedback');
setupValidation(form);
form.addEventListener('submit', event => {
  event.preventDefault();
  const name = document.getElementById('contactName');
  const message = document.getElementById('contactMessage');
  name.setCustomValidity(!name.value.trim() ? 'Enter your name.' : '');
  message.setCustomValidity(!message.value.trim() ? 'Enter your message.' : '');
  if (!validateForm(form, feedback)) return;
  const data = new FormData(form);
  const lines = ['Hello Dream Bakerz,', '', `Name: ${name.value.trim()}`];
  if (data.get('phone').trim()) lines.push(`Phone: ${data.get('phone').trim()}`);
  if (data.get('email').trim()) lines.push(`Email: ${data.get('email').trim()}`);
  lines.push(`Subject: ${data.get('subject')}`, '', message.value.trim(), '', 'Thank you.');
  openWhatsApp(lines.join('\n'));
});
form.querySelector('[type="submit"]').disabled = false;
