const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=process.env.TEST_URL || 'http://127.0.0.1:4173';
const out=path.resolve(__dirname,'../docs/verification');
const report={date:new Date().toISOString(),checks:[]};
const pass=name=>{report.checks.push(name);console.log('PASS',name);};
let browser;
(async()=>{
 browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{})});
 const page=await browser.newPage();
 for(const width of [320,375,390,430,768,1024,1440]){
  await page.setViewportSize({width,height:950});
  await page.goto(base+'/index.html');
  await page.waitForSelector('html.js');
  assert.match((await page.request.get(base+'/assets/icons/ui.svg')).headers()['content-type'],/image\/svg\+xml/);
  assert(await page.locator('.header-whatsapp').isVisible());
  assert.equal(await page.locator('.whatsapp-float').evaluate(e=>getComputedStyle(e).position),'fixed');
  assert.equal(await page.locator('.whatsapp-float').getAttribute('href'),'https://wa.me/923477268670');
  const size=await page.locator('.brand img').evaluate(e=>e.getBoundingClientRect().width);
  assert.equal(size,width<352?64:width<1024?76:96);
  assert.equal(await page.locator('.footer-identity img').count(),1);
  if(width<1024)await page.locator('#menuToggle').click();
  await page.locator('#cakeDropdown summary').click();
  assert(await page.locator('.nav-submenu').isVisible());
  assert.equal(await page.locator('.nav-submenu a').count(),3);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth));
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#cakeDropdown').getAttribute('open'),null);
  assert.equal(await page.evaluate(()=>document.activeElement.getAttribute('aria-label')),'Cake options');
  if(width<1024){
   await page.keyboard.press('Escape');
   assert.equal(await page.locator('#menuToggle').getAttribute('aria-expanded'),'false');
  }
  pass(`${width}px: larger logo, footer logo, two WhatsApp actions and keyboard dropdown without overflow`);
 }
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'/index.html');
 await page.evaluate(()=>document.fonts.ready);
 const typing=await page.locator('.typewriter').evaluate(e=>getComputedStyle(e,'::after').animationName);
 assert.equal(typing,'typewriter-wipe');
 pass('CSS typewriter animation preserves a single readable source string');
 await page.locator('.nav-link').first().hover();
 await page.waitForTimeout(250);
 assert.match(await page.locator('.nav-link').first().evaluate(e=>getComputedStyle(e,'::before').transform),/matrix\(1,/);
 await page.locator('.cake-image').first().hover();
 await page.waitForTimeout(300);
 const holo=await page.locator('.cake-image').first().evaluate(e=>({opacity:getComputedStyle(e,'::after').opacity,animation:getComputedStyle(e,'::after').animationName}));
 assert(Number(holo.opacity)>.5);assert.equal(holo.animation,'holographic-sweep');
 await page.locator('.story-copy h2').scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>document.querySelector('.story-copy h2').classList.contains('is-revealed'));
 assert.equal(await page.locator('.story-copy h2').evaluate(e=>getComputedStyle(e).animationName),'text-unveil');
 assert(await page.locator('.story-photo.scroll-reveal.is-revealed').count());
 pass('Creative navigation underline, holographic photo hover, scroll entrance and text reveal');
 await page.locator('.social-instagram').hover();
 await page.waitForTimeout(300);
 const social=await page.locator('.social-instagram').evaluate(e=>({background:getComputedStyle(e.querySelector('.social-label')).backgroundImage,paint:getComputedStyle(e.querySelector('svg')).getPropertyValue('--icon-paint'),transform:getComputedStyle(e.querySelector('svg')).transform}));
 assert(social.background.includes('linear-gradient'));assert(social.paint.includes('instagram-ink'));assert.notEqual(social.transform,'none');
 await page.locator('.whatsapp-float').hover();
 await page.waitForTimeout(300);
 assert.notEqual(await page.locator('.whatsapp-float svg').evaluate(e=>getComputedStyle(e).transform),'none');
 pass('Social media hover, gradient text/SVG ink and WhatsApp icon motion');
 await page.locator('.footer-identity img').evaluate(img=>img.decode());
 await page.locator('.site-footer').screenshot({path:path.join(out,'footer-update-1440.png')});
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 await page.waitForTimeout(800);
 await page.locator('.site-header').screenshot({path:path.join(out,'header-update-1440.png')});
 await page.locator('#cakeDropdown summary').click();
 await page.waitForTimeout(250);
 await page.screenshot({path:path.join(out,'dropdown-update-1440.png')});
 await page.locator('.hero-copy h1').click();assert.equal(await page.locator('#cakeDropdown').getAttribute('open'),null);
 pass('Dropdown closes on outside click; desktop header/footer screenshots saved');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto(base+'/index.html');
 assert.equal(await page.locator('.typewriter').evaluate(e=>getComputedStyle(e,'::after').display),'none');
 await page.locator('.cake-image').first().hover();
 assert.equal(await page.locator('.cake-image').first().evaluate(e=>getComputedStyle(e,'::after').display),'none');
 assert.equal(await page.locator('.scroll-progress').evaluate(e=>getComputedStyle(e).display),'none');
 assert.equal(await page.locator('.typewriter').textContent(),'Custom cakes in B-17, Islamabad');
 pass('Reduced motion disables typing cover, holographic sweep and scroll progress while content stays visible');
 const plain=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:950}});
 const nojs=await plain.newPage();await nojs.goto(base+'/index.html');
 await nojs.locator('#cakeDropdown summary').click();assert(await nojs.locator('.nav-submenu').isVisible());
 assert(await nojs.locator('.whatsapp-float').isVisible());
 await plain.close();pass('Native dropdown and fixed WhatsApp link work without JavaScript');
 report.result='PASS';
})().catch(error=>{report.result='FAIL';report.failure=error.stack;console.error(error);process.exitCode=1;}).finally(async()=>{
 if(browser)await browser.close();
 fs.writeFileSync(path.join(out,'interactions-report.json'),JSON.stringify(report,null,2)+'\n');
});
